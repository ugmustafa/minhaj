/** Индекс (0-based) суры, которая идёт на странице p (последняя начавшаяся не позже p). */
export function surahAtPage(p: number): number {
  let idx = 0;
  for (let i = 0; i < SURAH_START.length; i++) if (SURAH_START[i] <= p) idx = i; else break;
  return idx;
}

/** Все суры, текст которых есть на странице p. */
export function surahsOnPage(p: number): number[] {
  const res: number[] = [];
  for (let i = 0; i < SURAH_START.length; i++) {
    const s = SURAH_START[i];
    const next = SURAH_START[i + 1] ?? 605;
    if (s <= p && next >= p) res.push(i);
  }
  // сура, следующая за которой начинается ровно на p, считается продолжающейся,
  // кроме случая, когда на p начинается новая сура с первой строки (неизвестно) — оставляем.
  return res.length ? res : [surahAtPage(p)];
}

export function surahName(p: number): string {
  return SURAH_AR[surahAtPage(p)];
}

/** Последняя страница суры (с учётом того, что следующая может начаться на той же странице). */
export function surahLastPage(idx: number): number {
  const next = SURAH_START[idx + 1];
  return next === undefined ? 604 : next;
}
